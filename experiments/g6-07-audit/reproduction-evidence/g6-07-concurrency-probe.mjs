/**
 * E-CONCURRENCY — G6-07 Concurrency and Resource Exhaustion probe.
 *
 * Three scenarios, all run in-process against a real MissionService with
 * stub reasoning (no network, no OpenBot):
 *
 *   SCENARIO 1 — Concurrent submissions from one caller
 *     - 10 missions submitted via Promise.all() with one shared caller
 *       (per-caller cap = 20, so all should be admitted)
 *     - Reasoning stub sleeps 200 ms per call (2 calls per mission →
 *       ~400 ms per mission wall-clock if serial; ~400 ms total if
 *       parallel since the orchestrator's `await` points yield)
 *     - Verify: 10 distinct missionIds; all 10 reach terminal; health()
 *       reports activeMissions = 0 afterwards; capture timing.
 *
 *   SCENARIO 2 — Idempotency race
 *     - 5 concurrent submissions with the SAME idempotency key from the
 *       SAME caller. Verify either (a) only 1 mission is created and
 *       all 5 calls return the same missionId, or (b) a MissionAdmissionError
 *       is raised on the duplicates. The expected behavior per the code
 *       (mission-service.ts:192-204) is that ALL 5 should return the same
 *       missionId because `start()` is synchronous and the idempotency
 *       index check + set is atomic w.r.t. the event loop.
 *
 *   SCENARIO 3 — Concurrent cancellation of a slow mission
 *     - Submit 1 slow mission (2000 ms per step), then concurrently call
 *       cancel() 5 times on it. Verify the mission ends in CANCELLED
 *       (or PARTIAL if a deliverable was produced) — never FAILED, never
 *       SUCCEEDED, never stuck in CANCELLATION_REQUESTED.
 *
 * Run from the AgentCraft-Genesis repo root with node (ESM):
 *   node --experimental-vm-modules /home/z/my-project/scripts/g6-07-concurrency-probe.mjs
 *
 * Output: structured JSON summary on stdout.
 */
