/**
 * Reasoning provider whose `reason()` takes ~`delayMs` per call.
 * Two calls per mission: write_file then finish. Total per-mission wall
 * time ~ 2 * delayMs.
 */
function slowScriptedReasoning(delayMs = 200, label = 'SLOW_SCRIPTED') {
  let step = 0;
  return {
    name: label,
    async reason() {
      step += 1;
      await new Promise((r) => setTimeout(r, delayMs));
      if (step === 1) {
        return {
          text: JSON.stringify({
            action: 'write_file',
            path: 'output.md',
            contents: '# Probe output\n\nGenerated by the concurrency probe.\n',
          }),
        };
      }
      return {
        text: JSON.stringify({
          action: 'finish',
          summary: 'wrote output.md',
          artifacts: ['output.md'],
        }),
      };
    },
  };
}

/** Even slower reasoning — useful for the cancellation probe. */
function verySlowScriptedReasoning(delayMs = 2_000) {
  return slowScriptedReasoning(delayMs, 'VERY_SLOW_SCRIPTED');
}

// ---------------------------------------------------------------------------
// Caller identity
// ---------------------------------------------------------------------------

const CALLER = {
  callerId: 'conc-probe-caller',
  allowedOperations: ['mission:submit', 'mission:cancel'],
  maxActiveMissions: 20,
  maxMissionTimeoutMs: 30_000,
};

const CANCEL_CALLER = {
  callerId: 'cancel-probe-caller',
  allowedOperations: ['mission:submit', 'mission:cancel'],
  maxActiveMissions: 5,
  maxMissionTimeoutMs: 30_000,
};

const SIMPLE_GOAL =
  'Write a markdown file named output.md at the workspace root with the content "# Probe output" as the sole body.';

// ---------------------------------------------------------------------------
// Service builder — uses default memory runtime + injected reasoning.
// ---------------------------------------------------------------------------

function buildService(reasoningFactory) {
  return new MissionService({
    defaultMissionTimeoutMs: 30_000,
    maxActiveMissionsGlobal: 100,
    reasoningFactory,
  });
}

function nowMs() {
  return Date.now();
}

// ---------------------------------------------------------------------------
// SCENARIO 1: 10 concurrent submissions from one caller
// ---------------------------------------------------------------------------

async function scenario1_concurrentSubmissions() {
  console.log('--- SCENARIO 1: 10 concurrent submissions from one caller ---');
  const service = buildService(() => slowScriptedReasoning(200));

  const t0 = nowMs();
  // Fire 10 submissions concurrently. start() is synchronous, so all 10
  // should return immediately with distinct missionIds; the orchestrators
  // run in parallel in the background.
  const starts = await Promise.all(
    Array.from({ length: 10 }, (_, i) =>
      Promise.resolve().then(() => {
        const r = service.start(
          { outcome: `${SIMPLE_GOAL} (probe #${i})` },
          CALLER,
        );
        return { i, ...r };
      }),
    ),
  );
  const tStarts = nowMs();
  const startMs = tStarts - t0;

  // Distinct missionIds?
  const ids = starts.map((s) => s.missionId);
  const uniqueIds = new Set(ids);
  const distinctOk = uniqueIds.size === ids.length;
  console.log(
    `[starts] total=${starts.length} unique=${uniqueIds.size} distinctOk=${distinctOk} startMs=${startMs}ms`,
  );

  // Snapshot of active count immediately after all starts returned.
  const activeAfterStarts = service.health().activeMissions;
  console.log(`[health-after-starts] activeMissions=${activeAfterStarts}`);

  // Await all 10.
  const results = await Promise.all(
    starts.map(async (s) => {
      const snap = await service.awaitCompletion(s.missionId, CALLER);
      return { i: s.i, missionId: s.missionId, status: snap.status, terminal: snap.terminal };
    }),
  );
  const tEnd = nowMs();
  const awaitMs = tEnd - tStarts;
  const totalMs = tEnd - t0;

  // All terminal?
  const allTerminal = results.every((r) => r.terminal);
  const statusCounts = {};
  for (const r of results) {
    statusCounts[r.status] = (statusCounts[r.status] ?? 0) + 1;
  }

  // activeMissions returned to 0?
  const activeAfter = service.health().activeMissions;
  const totalAfter = service.health().totalMissions;
  console.log(
    `[done] allTerminal=${allTerminal} statusCounts=${JSON.stringify(statusCounts)} ` +
      `activeAfter=${activeAfter} totalAfter=${totalAfter} awaitMs=${awaitMs}ms totalMs=${totalMs}ms`,
  );

  // If parallel, totalMs should be roughly 2*200=400ms (not 10*400=4000ms).
  const parallelSpeedup = totalMs > 0 ? (10 * 400) / totalMs : 0;

  return {
    scenario: 'concurrent-submissions',
    submitted: starts.length,
    distinctMissionIds: uniqueIds.size,
    distinctOk,
    startMs,
    awaitMs,
    totalMs,
    activeAfterStarts,
    activeAfter,
    totalAfter,
    allTerminal,
    statusCounts,
    parallelSpeedupEstimate: parallelSpeedup,
    results,
  };
}

// ---------------------------------------------------------------------------
// SCENARIO 2: 5 concurrent submissions with the SAME idempotency key
// ---------------------------------------------------------------------------

async function scenario2_idempotencyRace() {
  console.log('\n--- SCENARIO 2: 5 concurrent submissions, same idempotency key ---');
  const service = buildService(() => slowScriptedReasoning(200));
  const idempotencyKey = 'conc-probe-idem-key-001';

  const t0 = nowMs();
  // Fire 5 submissions concurrently. They share the same key + caller.
  const outcomes = await Promise.all(
    Array.from({ length: 5 }, (_, i) =>
      Promise.resolve().then(() => {
        try {
          const r = service.start({ outcome: SIMPLE_GOAL, idempotencyKey }, CALLER);
          return { i, ok: true, missionId: r.missionId, status: r.status };
        } catch (e) {
          return { i, ok: false, error: e.name, message: e.message };
        }
      }),
    ),
  );
  const tStarts = nowMs();

  const successes = outcomes.filter((o) => o.ok);
  const failures = outcomes.filter((o) => !o.ok);
  const uniqueMissionIds = new Set(successes.map((o) => o.missionId));
  console.log(
    `[starts] success=${successes.length} fail=${failures.length} uniqueMissionIds=${uniqueMissionIds.size} startMs=${tStarts - t0}ms`,
  );
  for (const o of outcomes) {
    if (o.ok) {
      console.log(`  [${o.i}] OK missionId=${o.missionId} status=${o.status}`);
    } else {
      console.log(`  [${o.i}] FAIL ${o.error}: ${o.message}`);
    }
  }

  // Expected behavior: all 5 return the SAME missionId (start() is sync,
  // the index check + set is atomic w.r.t. the JS event loop).
  const allSameId =
    successes.length > 0 &&
    successes.every((o) => o.missionId === successes[0].missionId);

  // Total missions in the registry — should be exactly 1 if idempotency held.
  const totalAfter = service.health().totalMissions;
  console.log(
    `[verify] allSameId=${allSameId} totalMissions=${totalAfter} (expected 1)`,
  );

  // Await the (single) mission.
  let finalStatus = null;
  if (successes.length > 0) {
    const snap = await service.awaitCompletion(successes[0].missionId, CALLER);
    finalStatus = snap.status;
    console.log(`[awaited] finalStatus=${finalStatus}`);
  }

  const activeAfter = service.health().activeMissions;
  console.log(`[health] activeMissions=${activeAfter} totalMissions=${totalAfter}`);

  return {
    scenario: 'idempotency-race',
    submitted: 5,
    successes: successes.length,
    failures: failures.length,
    failureErrors: failures.map((f) => ({ error: f.error, message: f.message })),
    uniqueMissionIds: uniqueMissionIds.size,
    allSameId,
    totalMissions: totalAfter,
    finalStatus,
    activeAfter,
    outcomes,
  };
}

// ---------------------------------------------------------------------------
// SCENARIO 3: Concurrent cancellation of a slow mission
// ---------------------------------------------------------------------------

async function scenario3_concurrentCancellation() {
  console.log('\n--- SCENARIO 3: concurrent cancellation of a slow mission ---');
  const service = buildService(() => verySlowScriptedReasoning(2_000));

  // Submit one slow mission (2 s per step → ~4 s total if uninterrupted).
  const t0 = nowMs();
  const start = service.start({ outcome: SIMPLE_GOAL }, CANCEL_CALLER);
  const missionId = start.missionId;
  console.log(`[start] missionId=${missionId} status=${start.status}`);

  // Let the mission enter RUNNING.
  await new Promise((r) => setTimeout(r, 100));
  const beforeSnap = service.get(missionId, CANCEL_CALLER);
  console.log(`[pre-cancel] status=${beforeSnap.status} terminal=${beforeSnap.terminal}`);

  // Fire 5 cancel() calls concurrently.
  const tCancelStart = nowMs();
  const cancelResults = await Promise.all(
    Array.from({ length: 5 }, (_, i) =>
      Promise.resolve().then(() => {
        try {
          const status = service.cancel(missionId, CANCEL_CALLER);
          return { i, ok: true, status };
        } catch (e) {
          return { i, ok: false, error: e.name, message: e.message };
        }
      }),
    ),
  );
  const tCancelEnd = nowMs();
  const cancelMs = tCancelEnd - tCancelStart;
  console.log(`[cancels] elapsedMs=${cancelMs}`);
  for (const c of cancelResults) {
    if (c.ok) {
      console.log(`  [cancel ${c.i}] status=${c.status}`);
    } else {
      console.log(`  [cancel ${c.i}] FAIL ${c.error}: ${c.message}`);
    }
  }
  const cancelStatuses = cancelResults.filter((c) => c.ok).map((c) => c.status);

  // Await terminal.
  const snap = await service.awaitCompletion(missionId, CANCEL_CALLER);
  const tEnd = nowMs();
  const totalMs = tEnd - t0;

  console.log(
    `[final] status=${snap.status} terminal=${snap.terminal} result.status=${snap.result?.status} totalMs=${totalMs}ms`,
  );

  const activeAfter = service.health().activeMissions;
  const totalAfter = service.health().totalMissions;
  console.log(`[health] activeMissions=${activeAfter} totalMissions=${totalAfter}`);

  // Verdict: the mission MUST end in CANCELLED or PARTIAL — never FAILED,
  // never SUCCEEDED, never stuck in CANCELLATION_REQUESTED.
  const acceptableTerminal = ['CANCELLED', 'PARTIAL'];
  const verdict = acceptableTerminal.includes(snap.status);

  return {
    scenario: 'concurrent-cancellation',
    missionId,
    cancelCalls: 5,
    cancelOkCount: cancelResults.filter((c) => c.ok).length,
    cancelFailCount: cancelResults.filter((c) => !c.ok).length,
    cancelStatuses,
    cancelMs,
    finalStatus: snap.status,
    finalTerminal: snap.terminal,
    finalResultStatus: snap.result?.status,
    totalMs,
    activeAfter,
    totalAfter,
    verdict,
    cancelResults,
  };
}

