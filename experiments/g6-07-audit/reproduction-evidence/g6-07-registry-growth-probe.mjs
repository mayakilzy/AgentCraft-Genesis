/**
 * B-REGISTRY — G6-07 Mission Registry Memory Behavior Probe.
 *
 * Reproduces:
 *   1. Unbounded growth of `MissionService.missions` across the process
 *      lifetime, despite the G6-06 fix that evicted terminal missions
 *      from the admission count. We submit 100 missions sequentially
 *      (each completes before the next), so concurrent-active count
 *      never exceeds 1, yet `health().totalMissions` grows linearly.
 *   2. Admission control (active-only counting) still works for the
 *      concurrent case: 5 never-resolving missions pin all slots and
 *      the 6th is rejected; after one of the 5 settles the 6th succeeds.
 *   3. Idempotency key cannot be reused after the original mission
 *      reaches a terminal state, because `idempotencyIndex` is never
 *      cleaned either.
 *
 * Run from the AgentCraft-Genesis repo root with tsx:
 *   npx --yes tsx /home/z/my-project/scripts/g6-07-registry-growth-probe.mjs
 *
 * Output: structured JSON-ish log lines on stdout.
 */
import { MissionService } from '../audit-work/AgentCraft-Genesis/src/gateway/mission-service.js';
import { MemoryComputer } from '../audit-work/AgentCraft-Genesis/tests/helpers/memory-runtime.js';

// --- caller identity used by the probe ---
const caller = {
  callerId: 'probe-caller',
  allowedOperations: ['mission:submit'],
  maxActiveMissions: 50,
  maxMissionTimeoutMs: 30_000,
};

// A simple goal that the default scripted reasoning provider will complete.
const SIMPLE_GOAL =
  'Write a markdown file named output.md at the workspace root with the content "# Genesis gateway output" as the sole body.';

// --- helpers ---

function mb(bytes) {
  return (bytes / 1024 / 1024).toFixed(2) + ' MiB';
}

function heap() {
  // Force a GC pass if --expose-gc was supplied, so the retained
  // memory figure reflects only objects still reachable from the
  // service's missions Map.
  if (typeof global.gc === 'function') {
    global.gc();
    global.gc();
  }
  return process.memoryUsage().heapUsed;
}

// Reasoning provider whose `reason()` never resolves. Used to pin
// admission slots for the active-cap test.
function neverResolvingReasoning() {
  return {
    name: 'NEVER_RESOLVES',
    reason() {
      return new Promise(() => {
        /* never resolves */
      });
    },
  };
}

// Reasoning provider that resolves to a `finish` action after one
// `write_file`. Mirrors `buildDefaultReasoning()` but is stateful per
// instance so we can hand out fresh copies per mission.
function scriptedReasoning() {
  let step = 0;
  return {
    name: 'SCRIPTED',
    async reason() {
      step += 1;
      if (step === 1) {
        return {
          text: JSON.stringify({
            action: 'write_file',
            path: 'output.md',
            contents: '# Genesis gateway output\n\nGenerated by the gateway service.\n',
          }),
        };
      }
      return {
        text: JSON.stringify({
          action: 'finish',
          summary: 'wrote output.md',
          artifacts: ['output.md'],
        }),
      };
    },
  };
}

// Build a fresh MissionService with the same defaults as the gateway
// helpers test setup, but with explicit factories so we can swap the
// reasoning provider (for the never-resolving variant).
function buildService({ reasoningFactory } = {}) {
  return new MissionService({
    defaultMissionTimeoutMs: 10_000,
    maxActiveMissionsGlobal: 50,
    reasoningFactory,
    // Use the default memory runtime — MissionService.buildDefaultRuntime
    // wires MemoryComputer instances and captures them.
  });
}

// --- scenario 1: 100 sequential missions, registry growth ---
async function scenario1_sequentialGrowth() {
  console.log('--- SCENARIO 1: 100 sequential missions, registry growth ---');
  const service = buildService({ reasoningFactory: scriptedReasoning });

  const heapBefore = heap();
  const totalBefore = service.health().totalMissions;
  console.log(`[init] heapUsed=${mb(heapBefore)} totalMissions=${totalBefore}`);

  const samples = [];
  for (let i = 1; i <= 100; i++) {
    const { missionId } = service.start({ outcome: SIMPLE_GOAL }, caller);
    await service.awaitCompletion(missionId, caller);

    if (i % 10 === 0) {
      const h = service.health();
      samples.push({ step: i, totalMissions: h.totalMissions, activeMissions: h.activeMissions, heapUsed: heap() });
      console.log(
        `[step=${String(i).padStart(3, '0')}] totalMissions=${h.totalMissions} activeMissions=${h.activeMissions} heapUsed=${mb(heap())}`,
      );
    }
  }

  const heapAfter = heap();
  const totalAfter = service.health().totalMissions;
  const delta = heapAfter - heapBefore;
  console.log(
    `[done ] totalMissions=${totalAfter} activeMissions=${service.health().activeMissions} heapUsed=${mb(heapAfter)} delta=${mb(delta)}`,
  );

  return {
    scenario: 'sequential-growth',
    totalBefore,
    totalAfter,
    deltaMissions: totalAfter - totalBefore,
    heapBefore,
    heapAfter,
    heapDelta: delta,
    samples,
  };
}

// --- scenario 2: admission control with 5 never-resolving missions ---
async function scenario2_admissionControl() {
  console.log('\n--- SCENARIO 2: admission control with stuck missions ---');
  // Use a service where reasoning never resolves so missions stay RUNNING.
  const service = buildService({ reasoningFactory: neverResolvingReasoning });

  const stuck = [];
  for (let i = 1; i <= 5; i++) {
    const started = service.start({ outcome: SIMPLE_GOAL }, caller);
    stuck.push(started.missionId);
    console.log(`[stuck ${i}] missionId=${started.missionId} status=${started.status}`);
  }

  const h1 = service.health();
  console.log(
    `[after-5] activeMissions=${h1.activeMissions} totalMissions=${h1.totalMissions} (cap=50, caller cap=50)`,
  );

  // The 6th submission must be rejected because the global active cap is 50.
  // With cap=50 and 5 active, the 6th should actually be ADMITTED. To force
  // a rejection we lower the cap by using a tighter service. But to also
  // demonstrate the per-caller cap, set caller.maxActiveMissions = 5 and
  // verify the 6th is rejected by PER-CALLER admission (the more reliable
  // signal that active-only counting works).
  const tightCaller = {
    callerId: 'tight-caller',
    allowedOperations: ['mission:submit'],
    maxActiveMissions: 5,
    maxMissionTimeoutMs: 30_000,
  };
  const tightService = buildService({ reasoningFactory: neverResolvingReasoning });
  const tightStuck = [];
  for (let i = 1; i <= 5; i++) {
    const started = tightService.start({ outcome: SIMPLE_GOAL }, tightCaller);
    tightStuck.push(started.missionId);
  }
  const tightH = tightService.health();
  console.log(
    `[tight after-5] activeMissions=${tightH.activeMissions} totalMissions=${tightH.totalMissions} (per-caller cap=5)`,
  );

  // 6th submission should be rejected with admission denied.
  let sixthRejected = false;
  let sixthError = null;
  try {
    tightService.start({ outcome: SIMPLE_GOAL }, tightCaller);
  } catch (e) {
    sixthRejected = true;
    sixthError = e.message;
  }
  console.log(
    `[tight 6th] rejected=${sixthRejected} error=${sixthError} activeMissions=${tightService.health().activeMissions}`,
  );

  // Now cancel one of the 5 stuck missions and verify the 6th can succeed.
  // cancel() aborts the controller; with a never-resolving reasoning the
  // orchestrator's missionTimeoutMs (10s) still bounds the wait, but we
  // don't want to wait that long. Instead, verify the admission count
  // moves by cancelling — note that cancel() transitions to
  // CANCELLATION_REQUESTED (non-terminal), so it does NOT free the slot
  // until the orchestrator unwinds. We can't force the unwind without the
  // orchestrator running. So instead, re-test the GLOBAL cap, where the
  // path through countActiveGlobal excludes terminal missions: build a
  // fresh service, submit `cap-1` missions that DO complete, then verify
  // the next one (cap-th) is admitted.
  console.log('  (cancellation does not synchronously free slots; testing global active-only path instead)');

  const globalCap = 5;
  const globalService = new MissionService({
    defaultMissionTimeoutMs: 10_000,
    maxActiveMissionsGlobal: globalCap,
    reasoningFactory: scriptedReasoning,
  });
  const globalCaller = {
    callerId: 'global-caller',
    allowedOperations: ['mission:submit'],
    maxActiveMissions: 100, // generous; we want the GLOBAL cap to bind
    maxMissionTimeoutMs: 30_000,
  };
  // Submit `cap` missions sequentially. They complete; active count
  // should stay at 0 between iterations, and total grows.
  for (let i = 1; i <= globalCap * 4; i++) {
    const { missionId } = globalService.start({ outcome: SIMPLE_GOAL }, globalCaller);
    await globalService.awaitCompletion(missionId, globalCaller);
  }
  const globalH = globalService.health();
  console.log(
    `[global-after-${globalCap * 4}] totalMissions=${globalH.totalMissions} activeMissions=${globalH.activeMissions} (cap=${globalCap})`,
  );
  // After 20 sequential completions under a global cap of 5, the 21st
  // must still be ADMITTED — proving active-only counting excludes terminal
  // missions. If terminal missions were counted (the pre-G6-06 bug), the
  // 6th would have been rejected.
  let twentyFirstAdmitted = false;
  try {
    const r = globalService.start({ outcome: SIMPLE_GOAL }, globalCaller);
    twentyFirstAdmitted = true;
    await globalService.awaitCompletion(r.missionId, globalCaller);
  } catch (e) {
    twentyFirstAdmitted = false;
    console.log(`  [global 21st] rejected: ${e.message}`);
  }
  console.log(`[global 21st] admitted=${twentyFirstAdmitted}`);

  return {
    scenario: 'admission-control',
    tightCap: 5,
    tightActiveAfter5: tightService.health().activeMissions,
    sixthRejected,
    sixthError,
    globalCap,
    globalTotalAfter20: globalService.health().totalMissions,
    globalActiveAfter20: globalService.health().activeMissions,
    twentyFirstAdmitted,
  };
}

// --- scenario 3: idempotency key cannot be reused after terminal ---
async function scenario3_idempotencyReuse() {
  console.log('\n--- SCENARIO 3: idempotency key reuse after terminal ---');
  const service = buildService({ reasoningFactory: scriptedReasoning });
  const idempotencyKey = 'probe-idem-key-001';

  const r1 = service.start({ outcome: SIMPLE_GOAL, idempotencyKey }, caller);
  await service.awaitCompletion(r1.missionId, caller);
  console.log(`[first] missionId=${r1.missionId} terminal`);

  // Same caller resubmits the SAME idempotency key AFTER the original
  // mission has terminated. Pre-fix expectation: return the same
  // missionId (idempotent replay). Actual behavior: returns the same
  // missionId — but it is the TERMINAL mission, never a fresh run.
  // So the caller cannot "start a new mission with the same key" once
  // the original completes.
  const r2 = service.start({ outcome: SIMPLE_GOAL, idempotencyKey }, caller);
  console.log(`[reuse] sameMissionId=${r2.missionId === r1.missionId} status=${r2.status}`);
  const r3 = service.start({ outcome: SIMPLE_GOAL, idempotencyKey }, caller);
  console.log(`[reuse-again] sameMissionId=${r3.missionId === r1.missionId} status=${r3.status}`);

  // Idempotency index size — never cleaned.
  // Reach into the private field for measurement (probe-only).
  const idxSize = service.idempotencyIndex
    ? service.idempotencyIndex.size
    : '(private — count via health)';
  const total = service.health().totalMissions;
  console.log(`[index] totalMissions=${total} idempotencyIndexSize=${idxSize}`);

  return {
    scenario: 'idempotency-reuse',
    firstMissionId: r1.missionId,
    reuseReturnsSameId: r2.missionId === r1.missionId,
    reuseStatusIsTerminal: ['SUCCEEDED', 'FAILED', 'PARTIAL', 'CANCELLED'].includes(r2.status),
    reuseAgainReturnsSameId: r3.missionId === r1.missionId,
    totalMissions: total,
  };
}

